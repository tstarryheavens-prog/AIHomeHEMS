import sqlite3
import json
from datetime import datetime, timezone, timedelta

import os

DB_PATH = os.path.join(os.path.dirname(__file__), "hems.db")
JST = timezone(timedelta(hours=9))

def now_jst():
    """現在時刻を日本標準時(JST)でフォーマット取得"""
    return datetime.now(JST).strftime("%Y-%m-%d %H:%M:%S")

def get_connection():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn

def init_db():
    with get_connection() as conn:
        cursor = conn.cursor()
        
        # Real-time power metrics
        cursor.execute('''
            CREATE TABLE IF NOT EXISTS telemetry (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                timestamp DATETIME,
                grid_w REAL,
                pv_w REAL,
                cum_pv_kwh REAL,
                battery_w REAL,
                battery_soc REAL,
                battery_wh REAL,
                battery_mode TEXT
            )
        ''')

        # Room-by-room / Branch circuit power measurements
        cursor.execute('''
            CREATE TABLE IF NOT EXISTS room_telemetry (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                timestamp DATETIME,
                living_w REAL,
                aircon_w REAL,
                master_bed_w REAL,
                kids_room_w REAL,
                kitchen_w REAL,
                others_w REAL
            )
        ''')

        # HEMS Daily History
        cursor.execute('''
            CREATE TABLE IF NOT EXISTS hems_daily_history (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                date_str TEXT UNIQUE,
                cost_yen REAL,
                load_kwh REAL DEFAULT 0.0,
                buy_kwh REAL DEFAULT 0.0,
                sale_kwh REAL DEFAULT 0.0,
                pv_kwh REAL DEFAULT 0.0,
                self_kwh REAL DEFAULT 0.0,
                self_sufficiency_percent REAL DEFAULT 0.0,
                fetched_at DATETIME
            )
        ''')

        # Migration for energy breakdown columns
        cursor.execute("PRAGMA table_info(hems_daily_history)")
        d_cols = [row['name'] for row in cursor.fetchall()]
        for cname in ['buy_kwh', 'sale_kwh', 'pv_kwh', 'self_kwh']:
            if cname not in d_cols:
                cursor.execute(f"ALTER TABLE hems_daily_history ADD COLUMN {cname} REAL DEFAULT 0.0")

        # HEMS Monthly History
        cursor.execute('''
            CREATE TABLE IF NOT EXISTS hems_monthly_history (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                year_month TEXT UNIQUE,
                cost_yen REAL,
                load_kwh REAL DEFAULT 0.0,
                self_sufficiency_percent REAL,
                fetched_at DATETIME
            )
        ''')

        # Migration for load_kwh
        cursor.execute("PRAGMA table_info(hems_daily_history)")
        d_cols = [row['name'] for row in cursor.fetchall()]
        if 'load_kwh' not in d_cols:
            cursor.execute("ALTER TABLE hems_daily_history ADD COLUMN load_kwh REAL DEFAULT 0.0")

        cursor.execute("PRAGMA table_info(hems_monthly_history)")
        m_cols = [row['name'] for row in cursor.fetchall()]
        if 'load_kwh' not in m_cols:
            cursor.execute("ALTER TABLE hems_monthly_history ADD COLUMN load_kwh REAL DEFAULT 0.0")

        # Weather & Solar radiation forecast
        cursor.execute('''
            CREATE TABLE IF NOT EXISTS weather_forecast (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                fetched_at DATETIME DEFAULT CURRENT_TIMESTAMP,
                forecast_time DATETIME,
                shortwave_radiation REAL,
                cloud_cover REAL,
                est_pv_kwh REAL
            )
        ''')

        # Charge / Discharge schedule generated by optimizer
        cursor.execute('''
            CREATE TABLE IF NOT EXISTS daily_schedule (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
                target_date DATE,
                target_night_soc REAL,
                est_pv_kwh REAL,
                est_load_kwh REAL,
                details_json TEXT
            )
        ''')

        # Telemetry columns migration
        cursor.execute("PRAGMA table_info(telemetry)")
        cols = [row['name'] for row in cursor.fetchall()]
        if 'cum_pv_kwh' not in cols:
            cursor.execute("ALTER TABLE telemetry ADD COLUMN cum_pv_kwh REAL DEFAULT 0")
        if 'battery_wh' not in cols:
            cursor.execute("ALTER TABLE telemetry ADD COLUMN battery_wh REAL DEFAULT 0")
        conn.commit()

init_db()

def save_telemetry(grid_w, pv_w, battery_w, battery_soc, battery_mode="AUTO", cum_pv_kwh=0, battery_wh=0):
    with get_connection() as conn:
        cursor = conn.cursor()
        cursor.execute('''
            INSERT INTO telemetry (timestamp, grid_w, pv_w, cum_pv_kwh, battery_w, battery_soc, battery_wh, battery_mode)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        ''', (now_jst(), grid_w, pv_w, cum_pv_kwh, battery_w, battery_soc, battery_wh, battery_mode))
        conn.commit()

def save_room_telemetry(living_w, aircon_w, master_bed_w, kids_room_w, kitchen_w, others_w):
    with get_connection() as conn:
        cursor = conn.cursor()
        cursor.execute('''
            INSERT INTO room_telemetry (timestamp, living_w, aircon_w, master_bed_w, kids_room_w, kitchen_w, others_w)
            VALUES (?, ?, ?, ?, ?, ?, ?)
        ''', (now_jst(), living_w, aircon_w, master_bed_w, kids_room_w, kitchen_w, others_w))
        conn.commit()

def get_recent_telemetry(limit=50):
    with get_connection() as conn:
        cursor = conn.cursor()
        cursor.execute("SELECT * FROM telemetry ORDER BY timestamp DESC LIMIT ?", (limit,))
        return [dict(row) for row in cursor.fetchall()]

def get_hems_daily_history(limit=500, filter_zero=True):
    with get_connection() as conn:
        cursor = conn.cursor()
        if filter_zero:
            cursor.execute("SELECT * FROM hems_daily_history WHERE cost_yen > 0 ORDER BY date_str ASC LIMIT ?", (limit,))
        else:
            cursor.execute("SELECT * FROM hems_daily_history ORDER BY date_str ASC LIMIT ?", (limit,))
        return [dict(row) for row in cursor.fetchall()]

