def save_daily_schedule(target_date, target_night_soc, est_pv_kwh, est_load_kwh, details_dict):
    with get_connection() as conn:
        cursor = conn.cursor()
        cursor.execute('''
            INSERT INTO daily_schedule (target_date, target_night_soc, est_pv_kwh, est_load_kwh, details_json)
            VALUES (?, ?, ?, ?, ?)
        ''', (target_date, target_night_soc, est_pv_kwh, est_load_kwh, json.dumps(details_dict)))
        conn.commit()

def get_latest_schedule():
    with get_connection() as conn:
        cursor = conn.cursor()
        cursor.execute("SELECT * FROM daily_schedule ORDER BY created_at DESC LIMIT 1")
        row = cursor.fetchone()
        return dict(row) if row else None
